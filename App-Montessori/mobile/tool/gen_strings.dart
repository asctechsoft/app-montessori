// Generates lib/xml_strings/values/strings.xml (English, fallback) and
// lib/xml_strings/values-vi/strings.xml (Vietnamese) from tool/strings_src.dart.
//
// Usage (from mobile/):  dart run tool/gen_strings.dart
//
// The generated XML is Android-style (same format asc_common AscLocale reads):
// placeholders are %1$s, %2$s; apostrophes and quotes are backslash-escaped.
import 'dart:io';

import 'strings_src.dart';

String _esc(String v) => v
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"');

void main() {
  final root = Directory('lib/xml_strings');
  const targets = <(String, int)>[('values', 0), ('values-vi', 1)];
  final keys = kStrings.keys.toList()..sort();
  for (final (folder, idx) in targets) {
    final dir = Directory('${root.path}/$folder')..createSync(recursive: true);
    final b = StringBuffer()
      ..writeln('<?xml version="1.0" encoding="utf-8"?>')
      ..writeln(
        '<!-- Generated by tool/gen_strings.dart. Edit tool/strings_src.dart instead. -->',
      )
      ..writeln('<resources>');
    for (final k in keys) {
      final pair = kStrings[k]!;
      if (pair.length != 2) {
        stderr.writeln('Key "$k" must have exactly [English, Vietnamese].');
        exit(2);
      }
      b.writeln('    <string name="$k">${_esc(pair[idx])}</string>');
    }
    b.writeln('</resources>');
    File('${dir.path}/strings.xml').writeAsStringSync(b.toString());
  }
  stdout.writeln('${keys.length} keys written to ${targets.length} locale folders');
}
